"""Render outputs/results/tables/*.tex as a single HTML page for viewing without a LaTeX toolchain.

Table order follows the paper's own structure (TABLE_ORDER below), not the
alphabetical order run_analysis.R uses for its LaTeX compile-check wrapper.
"""

from pathlib import Path

from latex_table_html import render_tables

TABLES_DIR = Path("outputs/results/tables")
OUTPUT_HTML = Path("outputs/results/tables_preview.html")

# Presentation order, matching the paper rather than the alphabetical order in
# preview_all_tables.tex. Any .tex file in TABLES_DIR not listed here is
# appended at the end (and flagged), so a new table can't silently go missing.
TABLE_ORDER = [
    "demographics.tex",
    "child_demographics.tex",
    "reliability.tex",
    "subscale_descriptives.tex",
    "midpoint_comparison.tex",
    "correlations_general.tex",
    "correlations_bespoke.tex",
    "model_a_adjusted.tex",
    "model_a_estimated_means.tex",
    "comfort_distribution.tex",
    "model_b_blocks.tex",
    "model_b_coefficients_att.tex",
    "model_b_coefficients_intent.tex",
    "model_b_coefficients_intent_block4.tex",
    "model_b_tool_effect.tex",
    "model_c_coefficients.tex",
    "model_c_interaction_test.tex",
    "model_d_comfort.tex",
    "residual_diagnostics.tex",
    "supp_redundancy.tex",
]


def main():
    render_tables(
        tables_dir=TABLES_DIR,
        table_order=TABLE_ORDER,
        output_html=OUTPUT_HTML,
        title="Result tables",
        generated_note=(
            "Generated by render_tables.py from outputs/results/tables/*.tex. "
            "Do not edit by hand &mdash; rerun run_analysis.R then this script to refresh."
        ),
    )


if __name__ == "__main__":
    main()
