# Writes a compilable wrapper document containing every table fragment.
#
# The fragments are deliberately preamble-free so they can be \input{} into the
# manuscript, which means none of them compiles on its own. This wrapper supplies
# the minimum preamble and inputs them all, so the whole set can be previewed at
# once -- in Overleaf, or locally with LaTeX Workshop if a TeX distribution is
# installed.
#
# Regenerated on every run, so tables added or removed stay in sync.

# Runnable on its own: sets up the session if it is not already set up.
if (!exists("SETUP_DONE")) {
  .p <- normalizePath(getwd(), winslash = "/", mustWork = TRUE)
  while (!file.exists(file.path(.p, "R", "_setup.R"))) {
    if (identical(dirname(.p), .p)) stop("Run from inside the repository.")
    .p <- dirname(.p)
  }
  source(file.path(.p, "R", "_setup.R"))
}

message("08_preview")

# Tables are previewed in the order they appear in the manuscript where that
# order is known; anything not listed here (new tables, or ones whose
# manuscript position hasn't been pinned down yet) is appended afterwards in
# alphabetical order, so nothing silently goes missing from the preview.
MANUSCRIPT_TABLE_ORDER <- c(
  "demographics.tex", "child_demographics.tex", "reliability.tex",
  "model_a_adjusted.tex", "model_a_estimated_means.tex",
  "comfort_distribution.tex"
)
available <- list.files(TEX_DIR, pattern = "\\.tex$")
ordered <- intersect(MANUSCRIPT_TABLE_ORDER, available)
fragments <- c(ordered, sort(setdiff(available, ordered)))

preamble <- c(
  "% Preview wrapper for the result tables.",
  "% Generated by run_analysis.R -- do not edit by hand.",
  "%",
  "% This file exists only to render the table fragments for checking. The",
  "% fragments themselves carry no preamble so that they can be \\input{} into",
  "% the manuscript; the packages below are what they require.",
  "",
  "\\documentclass[11pt]{article}",
  "\\usepackage[margin=2cm]{geometry}",
  "\\usepackage{booktabs}",
  "\\usepackage{threeparttable}",
  "\\usepackage{rotating}      % only needed if a table is set landscape",
  "\\usepackage{caption}",
  "\\captionsetup[table]{labelfont=it,textfont=it,justification=raggedright,",
  "                     singlelinecheck=false}",
  "",
  "\\begin{document}",
  ""
)

body <- unlist(lapply(fragments, function(f) {
  c(sprintf("\\section*{\\ttfamily %s}", gsub("_", "\\\\_", f)),
    sprintf("\\input{tables/%s}", f),
    "\\clearpage",
    "")
}))

writeLines(
  c(preamble, body, "\\end{document}"),
  file.path(OUT_DIR, "preview_all_tables.tex")
)

message("  wrote outputs/results/preview_all_tables.tex (",
        length(fragments), " fragments)")
